    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_email_verifications_email_purpose UNIQUE (email, purpose),
    CONSTRAINT chk_email_verifications_attempt_count CHECK (attempt_count >= 0)
