CREATE TABLE IF NOT EXISTS problem_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS problem_category_links (
    problem_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_problem_category_links PRIMARY KEY (problem_id, category_id),
    CONSTRAINT fk_problem_category_links_problem
        FOREIGN KEY (problem_id) REFERENCES problems (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_problem_category_links_category
        FOREIGN KEY (category_id) REFERENCES problem_categories (id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS problem_test_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL,
    input_data CLOB NOT NULL,
    expected_output CLOB NOT NULL,
    sort_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_problem_test_cases_problem
        FOREIGN KEY (problem_id) REFERENCES problems (id)
);

CREATE TABLE IF NOT EXISTS problem_examples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL,
    input_data CLOB NOT NULL,
    expected_output CLOB NOT NULL,
    description CLOB,
    sort_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_problem_examples_problem
        FOREIGN KEY (problem_id) REFERENCES problems (id)
);

CREATE TABLE IF NOT EXISTS submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL,
    language VARCHAR(50) NOT NULL,
    source_code CLOB NOT NULL,
    status VARCHAR(30) NOT NULL,
    verdict VARCHAR(30),
    judge_message CLOB,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    judged_at TIMESTAMP,
    CONSTRAINT fk_submissions_problem
        FOREIGN KEY (problem_id) REFERENCES problems (id)
);

